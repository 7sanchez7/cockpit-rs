/// Le nom d'une langue, en minuscules ; None pour un code inconnu.
pub fn langue(code: &str) -> Option<&'static str> { chercher(&LANGUES, &code.to_ascii_lowercase()) }

/// Le nom d'un pays ; None pour un code inconnu.
pub fn pays(code: &str) -> Option<&'static str> { chercher(&PAYS, &code.to_ascii_uppercase()) }

fn chercher(table: &[(&str, &'static str)], code: &str) -> Option<&'static str> {
    table.binary_search_by(|(c, _)| (*c).cmp(code)).ok().map(|i| table[i].1)
}
